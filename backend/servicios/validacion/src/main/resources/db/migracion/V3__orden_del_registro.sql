-- DEF-04: orden estable del registro de la puerta.
-- La hora del escaneo se guarda sin fracción de segundo, así que dos escaneos del mismo segundo
-- empataban, y el desempate por id (un UUID al azar) daba cualquier orden. Esta columna la numera
-- la base en cada INSERT: sube siempre, nunca empata y respeta el orden en que se guardaron.
-- SQL compatible con PostgreSQL (Supabase) y con H2 en modo PostgreSQL. Los renglones que ya
-- existían reciben un número al agregar la columna.

alter table escaneo add column orden bigint generated by default as identity;

-- El registro se consulta por evento, del más nuevo al más viejo
create index escaneo_evento_orden_idx on escaneo (evento_id, escaneado, orden);
